// Runs the hero donut drop through the rigid-body simulation (js/donut-physics.js) and writes the result to
// js/donut-track.js. The page plays this baked track so the fall, the bounce and the landing are exactly the
// same on every phone and browser (floating-point maths differs slightly between engines, and a bouncing
// rigid body amplifies tiny differences).
//
//   node build-donut-track.mjs
//
// Change the start below, re-run, and check the printed events and final pose.
import { readFileSync, writeFileSync } from 'fs';
import { createSim, util } from './js/donut-physics.js';

const START = {
  x0: [1.22211, 0.2785, 1.6],          // box units: over the right half of the lid, toward the front, well above it
  v0: [0.49654, -0.06427, -1],         // already falling, drifting slightly right
  tiltAxis: [-0.36015, 0.96547, 0], tiltDeg: 181.49818,   // starts upside down...
  w0: [1.0667, 7.96391, -0.10406],     // ...and tumbles end over end, landing glaze-up
  popTorque: 29.12011, popDur: 0.131823, popGain: 1.723887
};
const P = Object.assign({}, START, { q0: util.qaxis(START.tiltAxis, START.tiltDeg * Math.PI / 180) });
const sim = createSim(P);
const FPS = 60, frames = [];
const r4 = v => Math.round(v * 1e4) / 1e4;
const ev = {};
for (let f = 0; f < FPS * 8; f++) {
  const b = sim.body;
  frames.push(...b.x.map(r4), ...b.q.map(v => Math.round(v * 1e5) / 1e5), Math.round(sim.lidDeg() * 100) / 100);
  for (const k of ['impact', 'pop', 'leftLid', 'ground', 'lidRest', 'sleep']) {
    if (ev[k] === undefined && sim.events[k] !== null) ev[k] = f;
  }
  if (sim.done() && ev.sleep !== undefined && f > ev.sleep + 2) break;
  sim.step(1 / FPS);
}
const n = frames.length / 8;
const out = `/* Generated by build-donut-track.mjs from js/donut-physics.js. Do not edit by hand. */
// per frame (${FPS} fps): x, y, z (box units), qx, qy, qz, qw (donut orientation), lid angle (degrees)
export default ${JSON.stringify({ fps: FPS, count: n, events: ev, frames })};
`;
writeFileSync(new URL('./js/donut-track.js', import.meta.url), out);
console.log('frames', n, 'events', JSON.stringify(ev), 'final', sim.body.x.map(r4), 'bytes', out.length);
